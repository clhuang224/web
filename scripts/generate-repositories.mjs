import { readFile, writeFile } from 'node:fs/promises'
import { createJiti } from 'jiti'

const jiti = createJiti(import.meta.url)
const { projects } = await jiti.import('../src/content/projects.ts')
const { parseRepository, repositoryFromSource } = await jiti.import(
  '../src/domain/repository.ts',
)
const target = 'src/content/generated/repositories.ts'

async function previous() {
  try {
    const module = await jiti.import(`../${target}`)
    return module.repositories
  } catch {
    return {}
  }
}

const headers = { Accept: 'application/vnd.github+json' }
if (process.env.GITHUB_TOKEN)
  headers.Authorization = `Bearer ${process.env.GITHUB_TOKEN}`

const earlier = await previous()
const repositories = {}
let fetched = 0
for (const name of projects.flatMap(
  (project) => repositoryFromSource(project.source) ?? [],
)) {
  const summary = await fetch(`https://api.github.com/repos/${name}`, {
    headers,
  })
    .then((response) => (response.ok ? response.json() : null))
    .then(parseRepository)
    .catch(() => null)
  if (summary) fetched += 1
  const kept = summary ?? earlier[name]
  if (kept) repositories[name] = kept
}

const output = `// Generated by scripts/generate-repositories.mjs. Run pnpm run generate:repositories to refresh.
import type { RepositorySummary } from '../../domain/repository'

export const repositories: Readonly<Record<string, RepositorySummary>> = ${JSON.stringify(repositories, null, 2)}
`
const { format, resolveConfig } = await import('prettier')
const formatted = await format(output, {
  ...(await resolveConfig(target)),
  parser: 'typescript',
})
const current = await readFile(target, 'utf8').catch(() => '')
if (current !== formatted) await writeFile(target, formatted)
console.log(
  `Fetched ${fetched} of ${Object.keys(repositories).length} repositories.`,
)
