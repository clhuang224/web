import { readFile, readdir, writeFile } from 'node:fs/promises'
import { watch } from 'node:fs'
import { parseMarkdownStory } from './lib/markdown-content.mjs'

const directory = new URL('../src/content/doodles/', import.meta.url)
const destination = new URL(
  '../src/content/generated/doodle-stories.ts',
  import.meta.url,
)
const aboutSource = new URL('../src/content/about.md', import.meta.url)
const aboutDestination = new URL(
  '../src/content/generated/about.ts',
  import.meta.url,
)

async function writeModule(target, declaration) {
  const output = `// Generated by scripts/generate-content.mjs. Edit the Markdown sources in src/content/.\nimport type { MarkdownStory } from '../../domain/markdown'\n\n${declaration}\n`
  const { format, resolveConfig } = await import('prettier')
  const formatted = await format(output, {
    ...(await resolveConfig(target.pathname)),
    parser: 'typescript',
  })
  let current = ''
  try {
    current = await readFile(target, 'utf8')
  } catch (error) {
    if (error.code !== 'ENOENT') throw error
  }
  if (current !== formatted) await writeFile(target, formatted)
}

async function generate() {
  const stories = {}
  for (const name of (await readdir(directory)).sort()) {
    if (!name.endsWith('.md')) continue
    if (!/^\d{2}\.md$/.test(name))
      throw new Error(`Invalid doodle content filename: ${name}`)
    try {
      stories[name.slice(0, -3)] = parseMarkdownStory(
        await readFile(new URL(name, directory), 'utf8'),
      )
    } catch (error) {
      throw new Error(`${name}: ${error.message}`, { cause: error })
    }
  }
  const about = parseMarkdownStory(await readFile(aboutSource, 'utf8'))
  await writeModule(
    destination,
    `export const doodleStories: Readonly<Partial<Record<string, MarkdownStory>>> = ${JSON.stringify(stories, null, 2)}`,
  )
  await writeModule(
    aboutDestination,
    `export const aboutStory: MarkdownStory = ${JSON.stringify(about, null, 2)}`,
  )
  console.log(
    `Generated About content and ${Object.keys(stories).length} doodle stories.`,
  )
}

await generate()
if (process.argv.includes('--watch')) {
  let pending = Promise.resolve()
  function regenerate() {
    pending = pending
      .then(generate)
      .catch((error) => console.error(error.message))
  }
  watch(directory, regenerate)
  watch(new URL('../src/content/', import.meta.url), (_, name) => {
    if (name === 'about.md') regenerate()
  })
}
